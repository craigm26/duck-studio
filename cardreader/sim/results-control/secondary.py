"""The secondary analysis declared after the falls control (docs/PACKS.md), before /5's rows were read.

    python3 cardreader/sim/results-control/secondary.py --base RUN [RUN ...] --after DIR [DIR ...]

Each RUN is a comma-joined triple raw,raw-acceptance,raw-back of one `/1` HF run; the runs are
pooled. For every row set and condition of `../results-walkback/compare.py`, and every criterion
counted over rows (position and heading: rows not within the bound; falls; time: rows with a late
card; ending badly: stopped rows without exactly one ending sentence), the candidate is "worse"
when its share of failing rows is above the pooled base's with a one-sided p below 0.05. Long
rows' position "rises" when the candidate's share within the bound is above the pooled base's
with a one-sided p below 0.05. The "worse" tests are one family, held to 0.05 together by Holm's
step-down correction (uncorrected flags are listed too); on `/1` against itself the uncorrected
rule flagged a place in one of the two directions.

Rows are not independent: `mc/mc_run.py` draws a condition's knobs (friction, mass, yaw bias and
drift) once per session of 12 rows, so rows of one session share a duck. The p values are
therefore a permutation test over SESSIONS (a session: one file, one knob draw, one block of 12
row indices), 4,000 permutations at a fixed seed, statistic the difference of pooled shares.
Fisher's exact test over rows, which treats rows as independent, is printed beside it for
comparison only.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "results-walkback"))
sys.path.insert(0, os.path.join(HERE, "..", "mc"))
import compare  # noqa: E402
import mc_summary as ms  # noqa: E402

LONG = ("every row, long (10 cards or more)", "randomized-10hz")


def fails(j):
    n = j["n"]
    return {"position": n - j["pos_ok"], "heading": n - j["head_ok"], "falls": j["falls"],
            "time": j["late"], "ending badly": j["bad"] - j["bad_said"]}


PERMS = 4000


def sessions(rows, crit):
    """(failing, rows) per session for one criterion; for "rises", passing position."""
    out = {}
    for r in rows:
        key = (r["_from"], json.dumps(r.get("knobs"), sort_keys=True), r["i"] // 12)
        j = ms.judge([r])
        k = j["pos_ok"] if crit == "rises" else fails(j)[crit]
        a, n = out.get(key, (0, 0))
        out[key] = (a + k, n + 1)
    return list(out.values())


def perm_greater(cand, base, seed=0):
    """One-sided permutation p over sessions: is the candidate's pooled share above the base's?"""
    def share(cs):
        n = sum(c[1] for c in cs)
        return sum(c[0] for c in cs) / n if n else 0.0
    obs = share(cand) - share(base)
    if not cand or not base or sum(c[0] for c in cand + base) == 0:
        return 1.0
    allc, m = cand + base, len(cand)
    rng = random.Random(seed)
    hit = 0
    for _ in range(PERMS):
        rng.shuffle(allc)
        if share(allc[:m]) - share(allc[m:]) >= obs - 1e-12:
            hit += 1
    return (hit + 1) / (PERMS + 1)


def lchoose(n, k):
    return math.lgamma(n + 1) - math.lgamma(k + 1) - math.lgamma(n - k + 1)


def fisher_greater(a, n1, b, n2):
    """P(first group's count >= a) under no difference: a of n1 against b of n2."""
    k, n = a + b, n1 + n2
    if n1 == 0 or n2 == 0 or k == 0:
        return 1.0
    den = lchoose(n, k)
    return min(1.0, sum(math.exp(lchoose(n1, x) + lchoose(n2, k - x) - den)
                        for x in range(a, min(k, n1) + 1)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", nargs="+", required=True)
    ap.add_argument("--after", nargs="+", required=True)
    ap.add_argument("--title", default="secondary analysis")
    a = ap.parse_args()
    bases = [compare.groups(r.split(",")) for r in a.base]
    after = compare.groups(a.after)
    lines = [f"# {a.title}", "", "Generated by `cardreader/sim/results-control/secondary.py` "
             "(one-sided Fisher exact, p < 0.05, base runs pooled).", "",
             "| row set | condition | criterion | base failing | candidate failing | sessions (base / candidate) | p, sessions | p, rows (Fisher) |",
             "|---|---|---|---|---|---|---|---|"]
    worse, tests, rows_out = [], [], []
    for key in after:
        ja = ms.judge(after[key])
        if ja["n"] == 0:
            continue
        jb = [ms.judge(b[key]) for b in bases]
        nb = sum(j["n"] for j in jb)
        fa = fails(ja)
        for crit, k in fa.items():
            kb = sum(fails(j)[crit] for j in jb)
            pf_ = fisher_greater(k, ja["n"], kb, nb)
            sc = sessions(after[key], crit)
            sb = [x for b in bases for x in sessions(b[key], crit)]
            p = perm_greater(sc, sb) if k * nb > kb * ja["n"] else 1.0
            tests.append((p, key, crit))
            rows_out.append([key, crit, kb, nb, k, ja["n"], len(sb), len(sc), p, pf_])
    m = len(tests)
    for rank, (p, key, crit) in enumerate(sorted(tests, key=lambda t: t[0])):
        if p >= 0.05 / (m - rank):
            break
        worse.append((key, crit))
    raw_flags = [(key, crit) for p, key, crit in tests if p < 0.05]
    for key, crit, kb, nb, k, n, lb, lc, p, pf_ in rows_out:
        flag = (key, crit) in worse
        lines.append(f"| {key[0]} | {key[1]} | {crit} | {kb}/{nb} | {k}/{n} | {lb} / {lc} | "
                     f"{'**' if flag else ''}{p:.3f}{'**' if flag else ''} | {pf_:.3f} |")
    ja = ms.judge(after[LONG])
    jb = [ms.judge(b[LONG]) for b in bases]
    ok_b, nb = sum(j["pos_ok"] for j in jb), sum(j["n"] for j in jb)
    p_rows = fisher_greater(ja["pos_ok"], ja["n"], ok_b, nb)
    p_rise = perm_greater(sessions(after[LONG], "rises"), [x for b in bases for x in sessions(b[LONG], "rises")])
    lines += ["", f"Long rows' position at randomized 10 Hz: base {ok_b}/{nb}, candidate "
              f"{ja['pos_ok']}/{ja['n']}, one-sided p (rises) = {p_rise:.4f} over sessions "
              f"({p_rows:.4f} over rows).", "",
              f"Uncorrected p < 0.05 in {len(raw_flags)} of {m} place(s): "
              + ("; ".join(f"{k[0]}, {k[1]}, {c}" for k, c in raw_flags) or "none") + ".", "",
              f"Worse (Holm, family of {m}) in {len(worse)} place(s): " + ("; ".join(f"{k[0]}, {k[1]}, {c}" for k, c in worse) or "none") + ".",
              "", "Secondary verdict: " + ("replaces the base" if not worse and p_rise < 0.05 else "does not replace the base") + "."]
    print("\n".join(lines))


if __name__ == "__main__":
    main()
