"""fcefea3 (duck-card-loop/1) beside this branch (duck-card-loop/2), criterion by criterion.

    python3 cardreader/sim/results-walkback/compare.py \\
        --before cardreader/sim/results/raw cardreader/sim/results/raw-acceptance cardreader/sim/results/raw-back \\
        --after cardreader/sim/results-walkback/raw cardreader/sim/results-walkback/raw-acceptance \\
                cardreader/sim/results-walkback/raw-back > cardreader/sim/results-walkback/COMPARE.md

Each side is grouped exactly as `../mc/mc_summary.py` groups it (the first directory is the run
over every row; the pre-registered rows exclude the Walk-back-only batch; the Walk back rows are
every row with a Walk back card from every directory) and judged by its `judge`, so the criteria
are docs/PACKS.md's "Acceptance", unchanged. Wilson 95% intervals on every share.
"""

from __future__ import annotations

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "mc"))
import mc_summary as ms  # noqa: E402
import rows as rowlist  # noqa: E402

CONDS = ["nominal", "randomized", "randomized-10hz", "stressed-10hz"]


def groups(dirs):
    every = ms.load(dirs[:1])
    allrows = ms.load(dirs)
    out = {}
    for c in CONDS:
        rs = allrows.get(c, [])
        acc = [r for r in rs if r["row"] in rowlist.ACCEPTANCE]
        out[("pre-registered rows", c)] = [r for r in acc if r["_from"] != "raw-back"]
        out[("Walk back rows", c)] = [r for r in acc if r["row"] in ms.WITH_BACK]
        out[("every row (packs' solutions included)", c)] = every.get(c, [])
        out[("every row, long (10 cards or more)", c)] = [r for r in every.get(c, []) if r["cards"] >= 10]
    return out


def share(k, n):
    if n == 0:
        return "n/a"
    lo, hi = ms.wilson(k, n)
    return f"{100 * k / n:.1f}% [{100 * lo:.1f}, {100 * hi:.1f}]"


def cell(j, crit):
    n = j["n"]
    if n == 0:
        return "no rows"
    p = j["pass"]
    if crit == "position":
        return f"{ms.pf(p['position'])} {j['pos_ok']}/{n} = {share(j['pos_ok'], n)}"
    if crit == "heading":
        return f"{ms.pf(p['heading'])} {j['head_ok']}/{n} = {share(j['head_ok'], n)}"
    if crit == "falls":
        return f"{ms.pf(p['falls'])} {j['falls']}/{n}, upper {100 * ms.wilson(j['falls'], n)[1]:.2f}%"
    if crit == "time":
        walk = max(j["walk_t"]) if j["walk_t"] else float("nan")
        turn = max(j["turn_t"]) if j["turn_t"] else float("nan")
        return f"{ms.pf(p['time'])} {j['late']} late (max Walk {walk:.2f} s, Turn {turn:.2f} s)"
    return f"{ms.pf(p['ending badly'])} {j['bad_said']}/{j['bad']}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--before", nargs="+", required=True)
    ap.add_argument("--after", nargs="+", required=True)
    a = ap.parse_args()
    before, after = groups(a.before), groups(a.after)
    lines = ["# duck-card-loop/1 (fcefea3) beside duck-card-loop/2 (the Walk lead)", "",
             "Generated by `cardreader/sim/results-walkback/compare.py`. Criteria: docs/PACKS.md, \"Acceptance\" "
             "(unchanged). Shares are the observed share of rows with the Wilson 95% interval in brackets. "
             "Before: " + ", ".join(f"`{d}`" for d in a.before) + ". After: " + ", ".join(f"`{d}`" for d in a.after) + ".", ""]
    sets = ["pre-registered rows", "Walk back rows", "every row (packs' solutions included)",
            "every row, long (10 cards or more)"]
    for st in sets:
        lines += [f"## {st}", "", "| condition | criterion | fcefea3, duck-card-loop/1 | this branch, duck-card-loop/2 |",
                  "|---|---|---|---|"]
        for c in CONDS:
            jb, ja = ms.judge(before[(st, c)]), ms.judge(after[(st, c)])
            for crit in ("position", "heading", "falls", "time", "ending badly"):
                lines.append(f"| {c} ({jb['n']} / {ja['n']} rows) | {crit} | {cell(jb, crit)} | {cell(ja, crit)} |")
        lines.append("")
        lines += [f"Errors over rows that finished, {st} (median / p95 / max):", "",
                  "| condition | position before (cm) | position after (cm) | heading before (deg) | heading after (deg) |",
                  "|---|---|---|---|---|"]
        for c in CONDS:
            jb, ja = ms.judge(before[(st, c)]), ms.judge(after[(st, c)])

            def d(xs):
                return "n/a" if not xs else f"{ms.q(xs, .5):.1f} / {ms.q(xs, .95):.1f} / {max(xs):.1f}"
            lines.append(f"| {c} | {d(jb['pos'])} | {d(ja['pos'])} | {d(jb['head'])} | {d(ja['head'])} |")
        lines.append("")
    # Rung 1, as docs/PACKS.md words it: every criterion in every condition, the Walk back rows on their own too.
    for name, g in (("fcefea3", before), ("this branch", after)):
        ok = all(all(ms.judge(g[(st, c)])["pass"].values()) for st in sets[:2] for c in CONDS)
        lines.append(f"- Rung 1 (pre-registered rows and Walk back rows, every criterion, every condition), {name}: "
                     f"**{'PASS' if ok else 'FAIL'}**")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
